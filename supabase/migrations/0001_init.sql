create table profiles (
  id uuid primary key references auth.users(id),
  display_name text,
  avatar_url text,
  created_at timestamptz default now()
);

create table songs (
  id bigint generated by default as identity primary key,
  title text not null,
  artist text not null,
  album text,
  duration int not null,
  color text,
  audio_url text,
  created_at timestamptz default now()
);

create table albums (
  id text primary key,
  title text,
  artist text,
  year int,
  color text,
  created_at timestamptz default now()
);

create table playlists (
  id text primary key,
  name text not null,
  owner_id uuid references profiles(id),
  cover text,
  system boolean default false,
  created_at timestamptz default now()
);

create table playlist_songs (
  playlist_id text references playlists(id) on delete cascade,
  song_id bigint references songs(id),
  position int,
  primary key (playlist_id, song_id)
);

alter table profiles enable row level security;
alter table songs enable row level security;
alter table albums enable row level security;
alter table playlists enable row level security;
alter table playlist_songs enable row level security;

create policy "profiles_select_all" on profiles for select using (true);
create policy "profiles_update_own" on profiles for update using (auth.uid() = id);

create policy "songs_select_all" on songs for select using (true);
create policy "albums_select_all" on albums for select using (true);

create policy "playlists_select_own_or_system" on playlists for select using (system = true or owner_id = auth.uid());
create policy "playlists_insert_own" on playlists for insert with check (owner_id = auth.uid());
create policy "playlists_update_own" on playlists for update using (owner_id = auth.uid()) with check (owner_id = auth.uid());
create policy "playlists_delete_own" on playlists for delete using (owner_id = auth.uid());

create policy "playlist_songs_select_if_readable" on playlist_songs for select using (
  exists (select 1 from playlists p where p.id = playlist_id and (p.system = true or p.owner_id = auth.uid()))
);
create policy "playlist_songs_insert_if_owned" on playlist_songs for insert with check (
  exists (select 1 from playlists p where p.id = playlist_id and p.owner_id = auth.uid())
);
create policy "playlist_songs_delete_if_owned" on playlist_songs for delete using (
  exists (select 1 from playlists p where p.id = playlist_id and p.owner_id = auth.uid())
);

create index playlists_owner_id_idx on playlists(owner_id);
create index playlist_songs_song_id_idx on playlist_songs(song_id);
create index songs_album_idx on songs(album);
create index songs_artist_idx on songs(artist);
create index albums_artist_idx on albums(artist);